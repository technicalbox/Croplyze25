/**
 * Look up medicines by name (case-insensitive partial match).
 */
export function searchMedicines(query: string): Medicine[] {
    const q = query.toLowerCase().trim();
    if (!q) return [];
    return medicineDictionary.filter(
        (m) =>
            m.name.toLowerCase().includes(q) ||
            m.activeIngredient.toLowerCase().includes(q) ||
            m.id.includes(q)
    );
}

/**
 * Get a single medicine by its ID.
 */
export function getMedicineById(id: string): Medicine | undefined {
    return medicineDictionary.find((m) => m.id === id);
}

/**
 * Get the full medicine dictionary as a compact string for AI prompts.
 */
export function getMedicineDictionaryContext(): string {
    return medicineDictionary
        .map(
            (m) =>
                `${m.name} (${m.activeIngredient}) — ${m.category} — Targets: ${m.targetDiseases.join(', ')} — Crops: ${m.recommendedCrops.join(', ')} — Effectiveness: ${m.effectivenessRange.min}–${m.effectivenessRange.max}% — Cost: ₹${m.averageCostPerAcre}/acre`
        )
        .join('\n');
}
